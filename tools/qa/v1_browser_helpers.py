"""R0036 V1 browser verification: Python helpers for tools/qa/r0036_v1_browser.cjs, run under v1_net_guard.

  font <out.ttf>          write the deterministic offline font fixture (fontTools, generated here; no download)
  compare <dir> <a> <b>   the original tests/v1_browser.py compare(), verbatim (Pillow), printed as JSON
  selftest                Python-side urlopen probes; prints what the guard refused (JSON)

The guard is installed before anything else runs. The font is a trivial fixture: glyphs .notdef and space only,
family name supplied by the caller's CSS; its bytes are a pure function of this file (fixed timestamps).
Licence/provenance: generated by this script, no third-party font data; dedicated to the public domain (CC0).
"""
import io
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import v1_net_guard  # noqa: E402

v1_net_guard.install()

FIXED_TIME = 3786825600  # 2024-01-01T00:00:00Z in seconds since 1904 (OpenType head epoch)


def font_bytes():
    from fontTools.fontBuilder import FontBuilder
    from fontTools.pens.ttGlyphPen import TTGlyphPen
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder([".notdef", "space"])
    fb.setupCharacterMap({0x20: "space"})
    pen = TTGlyphPen(None)
    pen.moveTo((100, 0)); pen.lineTo((100, 700)); pen.lineTo((500, 700)); pen.lineTo((500, 0)); pen.closePath()
    fb.setupGlyf({".notdef": pen.glyph(), "space": TTGlyphPen(None).glyph()})
    fb.setupHorizontalMetrics({".notdef": (600, 100), "space": (250, 0)})
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({"familyName": "R0036 V1 Fixture", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
    fb.setupPost()
    fb.setupHead(unitsPerEm=1000, created=FIXED_TIME, modified=FIXED_TIME)
    out = io.BytesIO()
    fb.font.save(out)
    return out.getvalue()


def compare(output, a, b):
    from PIL import Image, ImageChops
    im1, im2 = Image.open(output / a).convert("RGB"), Image.open(output / b).convert("RGB")
    diff = ImageChops.difference(im1, im2)
    raw = diff.tobytes()
    changed = sum(any(raw[i:i+3]) for i in range(0, len(raw), 3))
    maximum = max(raw)
    return {"changedPixels": changed, "totalPixels": im1.width * im1.height, "maxChannelDelta": maximum, "pixelExact": changed == 0}


def selftest():
    from urllib.request import urlopen
    results = []
    # 0.0.0.0 is refused locally by the OS even without the guard, so this probe can never leave the machine.
    probes = ["http://0.0.0.0:9/r0036-selftest"]
    if v1_net_guard.installed():
        probes.append("https://fonts.googleapis.com/css2?family=Inter")   # name probe only while the guard is proven active
    for url in probes:
        try:
            urlopen(url, timeout=2)
            results.append({"url": url, "refusedByGuard": False, "outcome": "connected"})
        except v1_net_guard.IsolationError as e:
            results.append({"url": url, "refusedByGuard": True, "outcome": str(e)})
        except Exception as e:  # noqa: BLE001 - any other failure is NOT a guard refusal
            results.append({"url": url, "refusedByGuard": "R0036 network isolation" in str(e), "outcome": type(e).__name__ + ": " + str(e)})
    return {"installed": v1_net_guard.installed(), "probes": results, "refused": v1_net_guard.REFUSED}


def main():
    cmd = sys.argv[1]
    if cmd == "font":
        data = font_bytes()
        Path(sys.argv[2]).write_bytes(data)
        import hashlib
        print(json.dumps({"bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(), "refused": v1_net_guard.REFUSED}))
    elif cmd == "compare":
        print(json.dumps({**compare(Path(sys.argv[2]), sys.argv[3], sys.argv[4]), "refused": v1_net_guard.REFUSED}))
    elif cmd == "selftest":
        print(json.dumps(selftest()))
    else:
        raise SystemExit("unknown command " + cmd)


if __name__ == "__main__":
    main()
